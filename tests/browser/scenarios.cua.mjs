export async function catalogFlows(tab) {
  await button(tab,'Overview').click();
  await tab.playwright.locator('#goal').selectOption('gym');
  await button(tab,'Plan my week').click();
  await button(tab,'Explore this look').click();
  await button(tab,'Save look').click();
  await button(tab,'Close dialog').click();
  await button(tab,'Lookbook').click();
  for(const variant of ['Warm','Cold','Gym','All looks']) await button(tab,variant).click();
  await tab.playwright.getByLabel('Search looks',{exact:true}).fill('no-such-style-fixture');
  assert(await tab.playwright.getByRole('heading',{name:'No looks found.',exact:true}).isVisible(),'Search empty state missing');
  await button(tab,'Clear filters').click();
  await tab.playwright.getByLabel('Filter by character').selectOption('Itachi Uchiha');
  assert((await tab.playwright.locator('.look-card').count())===9,'Character filter did not return nine looks');
  await tab.playwright.locator('.look-card .save-look').first().click();
  await tab.playwright.locator('.look-card .art-open').first().click();
  await button(tab,'Close dialog').click();
  await button(tab,'Saved looks').click();
  assert((await tab.playwright.locator('.look-card').count())>0,'Favorites did not persist');
  await button(tab,'Characters').click();
  await tab.playwright.getByRole('button',{name:'Explore looks',exact:true}).first().click();
  assert((await tab.playwright.locator('.look-card').count())>0,'Character navigation failed');
  await button(tab,'Characters').click();
  await tab.playwright.locator('.matrix-item').last().click();
  assert(await tab.playwright.getByRole('heading',{name:'Signature palette',exact:true}).isVisible(),'Character reference missing');
  await button(tab,'Create a casual interpretation').click();
  await tab.playwright.getByLabel('Look name',{exact:true}).fill('Coverage custom look');
  await tab.playwright.getByLabel('Character',{exact:true}).fill('Coverage fixture');
  await tab.playwright.getByLabel('Series',{exact:true}).fill('Synthetic tests');
  await tab.playwright.getByLabel('Outfit pieces · one per line',{exact:true}).fill('Plain black tee\nPlain olive shorts\nBlack sneakers\nViolet watch');
  await tab.playwright.getByLabel('Styling note',{exact:true}).fill('Synthetic fixture only.');
  await button(tab,'Add to my wardrobe').click();
  await button(tab,'Lookbook').click();
  await tab.playwright.getByLabel('Search looks',{exact:true}).fill('Coverage custom look');
  assert((await tab.playwright.locator('.look-card').count())===1,'Custom look missing');
  await tab.playwright.locator('.look-card .art-open').click();
  assert(await tab.playwright.getByRole('heading',{name:'Coverage custom look',exact:true}).isVisible(),'Custom detail missing');
  await button(tab,'Close dialog').click();
  return ['catalog filters and empty state','favorites','character and reference navigation','custom look creation and placeholder'];
}
