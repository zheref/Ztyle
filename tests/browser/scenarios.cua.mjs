export async function backupAndUploadFlows(tab,{imagePath,invalidBackupPath}) {
  await button(tab,'Settings & storage').click();
  let pending=tab.playwright.waitForEvent('download');
  await button(tab,'Export backup').click();
  const backupPath=await (await pending).path();
  pending=tab.playwright.waitForEvent('download');
  await button(tab,'Export calendar from before the matrix correction').click();
  await pending;
  let chooser=tab.playwright.waitForEvent('filechooser');
  await button(tab,'Import backup').click();
  await (await chooser).setFiles([backupPath]);
  await button(tab,'Restore backup').click();
  assert((await tab.playwright.locator('.toast').innerText()).includes('restored'),'Restore feedback missing');
  chooser=tab.playwright.waitForEvent('filechooser');
  await button(tab,'Import backup').click();
  await (await chooser).setFiles([invalidBackupPath]);
  assert(await tab.playwright.locator('.toast').isVisible(),'Invalid backup feedback missing');
  await button(tab,'Close dialog').click();
  await button(tab,'Add a look').click();
  chooser=tab.playwright.waitForEvent('filechooser');
  await tab.playwright.getByLabel('Illustration · optional',{exact:true}).click();
  await (await chooser).setFiles([invalidBackupPath]);
  assert((await tab.playwright.getByRole('dialog').innerText()).includes('Choose a PNG'),'Image validation missing');
  chooser=tab.playwright.waitForEvent('filechooser');
  await tab.playwright.getByLabel('Illustration · optional',{exact:true}).click();
  await (await chooser).setFiles([imagePath]);
  for(const field of ['Look name','Character','Outfit pieces · one per line'])await tab.playwright.getByLabel(field,{exact:true}).fill(' ');
  await button(tab,'Add to my wardrobe').click();
  assert((await tab.playwright.getByRole('dialog').innerText()).includes('Add a look name'),'Whitespace validation missing');
  await tab.playwright.getByLabel('Look name',{exact:true}).fill('Illustrated coverage fixture');
  await tab.playwright.getByLabel('Character',{exact:true}).fill('Fixture');
  await tab.playwright.getByLabel('Outfit pieces · one per line',{exact:true}).fill('Black tee');
  await button(tab,'Add to my wardrobe').click();
  return ['backup exports and confirmed restore','invalid backup feedback','artwork upload and validation','trimmed form validation and default styling'];
}
